package Loops;

public class ForLoop {

    public static void main(String[] args) {
        for (int i = 1; i <= 100; i++) {
            if (i % 10 == 0) {
                System.out.println(" Welcome to the House Of JAVA ");

            } else {
                System.out.print(" Welcome Umesh ");

            }
        }
    }
}

